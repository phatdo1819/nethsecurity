"""
Login page backend for the WireGuard servers that require user credentials.

Usage: ns-wgauth COMMAND

  sync            apply the configuration: create or update the nftables gate and the nginx server, end the
                  sessions no longer valid
  serve           run the login API on a unix socket, behind nginx
  check           test the nftables rules and the nginx configuration, report the state of the gate
  needed          exit with 0 if at least one WireGuard server requires the login
  status          print the open sessions as JSON
  logout PEER     end the session of a peer, PEER is the peer section name
  alerts          print the suspected copies and the lockouts of the peers as JSON
  clear PEER      forget the alerts of a peer and unblock it
  devices         print the devices enrolled and the enrollments open as JSON
"""

import ipaddress
import json
import os
import shutil
import socket
import socketserver
import subprocess
import sys
import syslog
import threading
import time
from datetime import UTC, datetime
from http.server import BaseHTTPRequestHandler

from euci import EUci
from nethsec import wgauth

SOCKET = "/var/run/ns-wgauth.sock"
NGINX_CONF = "/etc/nginx/conf.d/ns-wgauth.conf"
NGINX_MAIN_CONF = "/etc/nginx/uci.conf"
WEB_ROOT = "/www-wgauth"
# seconds between two checks of the endpoints, see wgauth.CopyDetector
WATCH_INTERVAL = 5
# seconds between two checks of the gate and of the sessions: also the longest time a copied configuration can
# share a session with lock_endpoint set to strict
SYNC_INTERVAL = 15
MAX_BODY = 4096
OTP_REUSE_WINDOW = 120

# the limit counts the requests of a VPN address, shared by every copy of a configuration: it only stops floods,
# the failed logins are counted by the daemon for each public IP
NGINX_TEMPLATE = """# Generated by ns-wgauth from /etc/config/ns-wgauth, do not edit
limit_req_zone $binary_remote_addr zone=ns_wgauth:1m rate=30r/m;

server {{
	listen {port};
	server_name _;
	root {root};
	access_log off;
	error_log syslog:server=unix:/dev/log,nohostname;
	server_tokens off;
	client_max_body_size 4k;
	add_header Cache-Control "no-store" always;
	add_header X-Content-Type-Options "nosniff" always;
	add_header X-Frame-Options "DENY" always;
	add_header Content-Security-Policy "default-src 'self'; frame-ancestors 'none'" always;

	location = / {{
		try_files /index.html =404;
	}}

	location / {{
		try_files $uri =404;
	}}

	location = /api/login {{
		limit_req zone=ns_wgauth burst=10 nodelay;
		limit_req_status 429;
		proxy_set_header X-Real-IP $remote_addr;
		proxy_set_header X-Forwarded-Host $http_host;
		proxy_pass http://unix:{socket};
	}}

	location /api/ {{
		proxy_set_header X-Real-IP $remote_addr;
		proxy_set_header X-Forwarded-Host $http_host;
		proxy_pass http://unix:{socket};
	}}
}}
"""

# nftables redirects here the web requests of the peers that aren't logged in: $server_addr is then the address of
# the WireGuard server the request came through
NGINX_REDIRECT_TEMPLATE = """
server {{
	listen {redirect_port};
	server_name _;
	access_log off;
	error_log syslog:server=unix:/dev/log,nohostname;
	server_tokens off;
	add_header Cache-Control "no-store" always;
	return 302 http://$server_addr:{port}/;
}}
"""


def iso_time(timestamp):
    return datetime.fromtimestamp(timestamp, tz=UTC).isoformat()


def read_file(path):
    try:
        with open(path) as fp:
            return fp.read()
    except FileNotFoundError:
        return None


def write_file(path, content):
    if content is None:
        if os.path.exists(path):
            os.remove(path)
        return
    with open(path, "w") as fp:
        fp.write(content)


def nginx_test():
    process = subprocess.run(["nginx", "-t", "-c", NGINX_MAIN_CONF], check=False, capture_output=True, text=True)
    return process.returncode == 0, process.stderr.strip()


def update_nginx(state):
    """
    Write the nginx server of the login page, remove it when no server requires the login.
    A configuration that nginx refuses is removed: the administration UI is served by the same nginx.
    """
    content = None
    if state["servers"]:
        content = NGINX_TEMPLATE.format(port=state["port"], root=WEB_ROOT, socket=SOCKET)
        if state["redirect"]:
            content += NGINX_REDIRECT_TEMPLATE.format(port=state["port"], redirect_port=state["redirect_port"])
    previous = read_file(NGINX_CONF)
    if previous == content:
        return
    write_file(NGINX_CONF, content)
    # at boot nginx hasn't generated its configuration yet: it will read the new file when it starts
    if os.path.exists(NGINX_MAIN_CONF):
        valid, message = nginx_test()
        if not valid:
            write_file(NGINX_CONF, previous)
            wgauth.log(f"nginx refused the login page configuration: {message}", syslog.LOG_ERR)
            return
    if subprocess.run(["/etc/init.d/nginx", "running"], check=False, capture_output=True).returncode == 0:
        subprocess.run(["/etc/init.d/nginx", "reload"], check=False, capture_output=True)


# one (modification time, snapshot) pair, replaced as a whole: the threads share it
_state_cache = [(None, None)]


def current_state():
    """The configuration applied last, see wgauth.build_state, read again only when `sync` writes it."""
    try:
        stamp = os.stat(wgauth.STATE_FILE).st_mtime_ns
    except OSError:
        stamp = None
    cached_stamp, cached_state = _state_cache[0]
    if stamp is not None and cached_stamp == stamp:
        return cached_state
    state = wgauth.load_state()
    if state is None:
        return wgauth.build_state(EUci())
    _state_cache[0] = (stamp, state)
    return state


def sync(apply=True):
    """
    With `apply`, take the configuration and make it the one the login service works on: the init script does it
    at boot and every time the configuration is applied. Without, check that the gate and the sessions match the
    configuration applied last, ignoring the changes saved but not applied yet.
    """
    with wgauth.state_lock():
        state = None if apply else wgauth.load_state()
        if state is None:
            uci = EUci()
            state = wgauth.build_state(uci)
            wgauth.save_state(state)
            wgauth.prune_alerts(uci)
        wgauth.apply_ruleset(state, force=apply)
        update_nginx(state)
        # opens the enrollment of the new peers of the servers that require device binding
        wgauth.sync_devices(state)
        wgauth.reconcile(state)
    return state


class LoginService:
    """The login API: every method returns an HTTP status and a JSON object."""

    def __init__(self):
        self.lock = threading.Lock()
        self.failures = wgauth.LoginFailures()
        self.detector = wgauth.CopyDetector()
        self.challenges = wgauth.Challenges()
        # peer -> time of the latest alert for a login from another device
        self.mismatches = {}
        # (database, user) -> {code: timestamp}, an OTP code works only once
        self.used_codes = {}

    @staticmethod
    def target(state, address, host):
        """
        Return the server and the peer entry of the client, `(None, None)` if it can't use the login page.
        The page must be opened with the address of the server: a page of another site whose name resolves to
        that address (DNS rebinding) is refused.
        """
        if address is None:
            return None, None
        server, peer = wgauth.find_peer(state, address)
        if server is None:
            return None, None
        server_address = state["servers"][server]["address"]
        if host not in (server_address, f"{server_address}:{state['port']}"):
            return None, None
        return server, peer

    def status(self, address, host):
        state = current_state()
        server, peer = self.target(state, address, host)
        if server is None:
            return 403, {"error": "forbidden"}
        config = state["servers"][server]
        result = {
            "authenticated": False,
            "otp_required": config["otp"],
            "server": config["name"],
            "blocked": wgauth.is_blocked(peer),
            "no_user": not peer["user"],
            "no_otp": wgauth.otp_missing(state, server, peer),
        }
        if config["device_binding"]:
            entry = wgauth.peer_device(wgauth.load_devices(), peer["peer"], peer["public_key"])
            device_state = wgauth.device_state(entry)
            # only an app that signs can log in, the browser explains it
            result["device"] = {
                "required": True,
                "enrolled": device_state == "enrolled",
                "enrollment_open": device_state == "waiting",
                "machine_id": config["machine_id"],
                "challenge": self.challenges.issue(address, int(time.time())),
            }
        left = wgauth.list_sessions().get(server, {}).get(address)
        if left is not None:
            entry = wgauth.load_metadata().get(server, {}).get(address, {})
            result["authenticated"] = True
            result["user"] = entry.get("user", "")
            result["expires"] = iso_time(time.time() + left)
        return 200, result

    def failed(self, state, server, address, peer, endpoint, username, now, reason="invalid_credentials"):
        """Count a failed login, lock out its IP after too many, return the answer."""
        lockout_time = state["lockout_time"]
        locked = self.failures.add(peer["peer"], endpoint, now, state["max_failures"], lockout_time)
        name = username[:64] if isinstance(username, str) else ""
        wgauth.log(
            f"login failed: user={name!r} server={server} peer={peer['peer']} address={address} from={endpoint}"
            + ("" if reason == "invalid_credentials" else f" reason={reason}"),
            syslog.LOG_WARNING,
        )
        if locked:
            wgauth.log(
                f"peer {peer['peer']} of user={peer['user']} locked out for {lockout_time} seconds "
                f"from {', '.join(ip or 'an unknown IP' for ip in locked)}",
                syslog.LOG_WARNING,
            )
            wgauth.add_alert(peer["peer"], peer["public_key"], "lockout", peer["user"], locked)
        return 401, {"error": reason}

    def check_device(self, state, server, address, peer, data, now):
        """
        Check the device of a login on a server that requires device binding, before the password.
        Returns `(error, None)` to refuse the login, `(None, device)` to go on, `device` being the one to enroll.
        """
        proof = data.get("device")
        if not isinstance(proof, dict):
            return "device_required", None
        if not self.challenges.use(address, proof.get("challenge"), now):
            # the app asks for a new one and tries again
            return "challenge_expired", None
        entry = wgauth.peer_device(wgauth.load_devices(), peer["peer"], peer["public_key"])
        error, enrolling = wgauth.verify_device(state, server, address, peer, data.get("username"), proof, entry, now)
        if error == "device_not_enrolled":
            wgauth.log(
                f"login refused: peer={peer['peer']} of user={peer['user']} has no device and can't enroll one",
                syslog.LOG_WARNING,
            )
        return error, enrolling

    def report_mismatch(self, peer, endpoint, now):
        """An alert for a login from another device, at most once every COPY_REPORT_INTERVAL for each peer."""
        with self.lock:
            if now - self.mismatches.get(peer["peer"], 0) < wgauth.COPY_REPORT_INTERVAL:
                return
            self.mismatches[peer["peer"]] = now
        wgauth.log(
            f"peer {peer['peer']} of user={peer['user']} tried to log in from another device", syslog.LOG_WARNING
        )
        wgauth.add_alert(peer["peer"], peer["public_key"], "device_mismatch", peer["user"], [endpoint])

    def code_reused(self, state, server, peer, code, now):
        key = (state["servers"][server]["database"], peer["user"].lower())
        with self.lock:
            codes = {
                used: moment for used, moment in self.used_codes.get(key, {}).items() if now - moment < OTP_REUSE_WINDOW
            }
            reused = code in codes
            if not reused:
                codes[code] = now
            self.used_codes[key] = codes
        return reused

    def login(self, address, host, data):
        state = current_state()
        server, peer = self.target(state, address, host)
        if server is None:
            return 403, {"error": "forbidden"}
        if wgauth.is_blocked(peer):
            return 403, {"error": "blocked"}
        if not peer["user"]:
            return 403, {"error": "no_user"}
        if wgauth.otp_missing(state, server, peer):
            return 403, {"error": "no_otp"}
        now = time.time()
        # the public IP of the client: the request just came through the tunnel
        endpoint = (wgauth.read_endpoints() or {}).get(peer["public_key"], "")
        max_failures = state["max_failures"]
        lockout_time = state["lockout_time"]
        until = self.failures.locked_until(peer["peer"], endpoint, now, max_failures, lockout_time)
        if until is not None:
            return 429, {"error": "too_many_attempts", "retry_after": max(int(until - now), 1)}
        username = data.get("username")
        binding = state["servers"][server]["device_binding"]
        enrolling = None
        if binding:
            # before the password: from another device, the password is never checked
            error, enrolling = self.check_device(state, server, address, peer, data, int(now))
            if error == "device_mismatch":
                self.report_mismatch(peer, endpoint, int(now))
                return self.failed(state, server, address, peer, endpoint, username, now, error)
            if error == "challenge_expired":
                return 401, {"error": error}
            if error is not None:
                return 403, {"error": error}
        otp = data.get("otp", "")
        valid = wgauth.check_login(state, server, peer, username, data.get("password"), otp)
        if valid and state["servers"][server]["otp"] and self.code_reused(state, server, peer, otp, now):
            valid = False
        if not valid:
            return self.failed(state, server, address, peer, endpoint, username, now)
        if binding:
            machine_id = data["device"].get("machine_id", "") if state["servers"][server]["machine_id"] else ""
            if not wgauth.record_device_login(peer, enrolling, machine_id, endpoint, int(now)):
                # another device enrolled meanwhile, or the window closed
                return self.failed(state, server, address, peer, endpoint, username, now, "device_mismatch")
        self.failures.success(peer["peer"], endpoint)
        expires = wgauth.open_session(state, server, address, peer, endpoint)
        return 200, {"result": "success", "user": peer["user"], "expires": iso_time(expires)}

    def logout(self, address, host, data):
        state = current_state()
        server, _peer = self.target(state, address, host)
        if server is None:
            return 403, {"error": "forbidden"}
        wgauth.close_session(server, address, "logout")
        return 200, {"result": "success"}

    def watch(self, state):
        """End the session of the peers whose key looks used by two devices, see wgauth.CopyDetector."""
        if not state["detect_copies"]:
            return
        endpoints = wgauth.read_endpoints()
        if endpoints is None:
            return
        keys = {peer["public_key"] for config in state["servers"].values() for peer in config["peers"].values()}
        watched = {key: address for key, address in endpoints.items() if key in keys}
        for public_key, addresses in self.detector.observe(watched, time.time()).items():
            wgauth.report_copy(state, public_key, addresses)


class Handler(BaseHTTPRequestHandler):
    server_version = "ns-wgauth"
    sys_version = ""
    # seconds, nginx sends the whole request at once
    timeout = 10

    def log_message(self, format, *args):
        # logins are logged by LoginService, nothing else is worth it
        pass

    def address_string(self):
        return self.headers.get("X-Real-IP", "-") if getattr(self, "headers", None) else "-"

    def client_ip(self):
        # nginx sets the header, the socket is reachable only by root
        try:
            return str(ipaddress.IPv4Address(self.headers.get("X-Real-IP", "")))
        except ValueError:
            return None

    def host(self):
        return self.headers.get("X-Forwarded-Host", "")

    def route(self):
        return self.path.split("?", 1)[0]

    def send_json(self, status, data):
        body = json.dumps(data).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def read_json(self):
        # a form on another site can't send application/json without a CORS preflight, which this API never answers
        if self.headers.get_content_type() != "application/json":
            return None
        try:
            length = int(self.headers.get("Content-Length", "0"))
        except ValueError:
            return None
        if length < 0 or length > MAX_BODY:
            return None
        try:
            data = json.loads(self.rfile.read(length) or b"{}")
        except ValueError:
            return None
        return data if isinstance(data, dict) else None

    def call(self, method, *args):
        try:
            self.send_json(*method(self.client_ip(), self.host(), *args))
        except Exception as error:  # noqa: BLE001 answer the client and keep serving
            wgauth.log(f"request failed: {self.route()}: {error}", syslog.LOG_ERR)
            self.send_json(500, {"error": "internal_error"})

    def do_GET(self):
        if self.route() == "/api/status":
            self.call(self.server.service.status)
        else:
            self.send_json(404, {"error": "not_found"})

    def do_POST(self):
        methods = {"/api/login": self.server.service.login, "/api/logout": self.server.service.logout}
        method = methods.get(self.route())
        if method is None:
            self.send_json(404, {"error": "not_found"})
            return
        data = self.read_json()
        if data is None:
            self.send_json(400, {"error": "invalid_request"})
            return
        self.call(method, data)


def run_logged(errors, name, task):
    """Run a task of the monitor loop: an error is logged once, until the task works again."""
    try:
        task()
    except Exception as error:  # noqa: BLE001 the loop must survive any error and retry
        message = str(error)
        if errors.get(name) != message:
            wgauth.log(f"{name} failed: {message}", syslog.LOG_ERR)
            errors[name] = message
    else:
        if errors.pop(name, None) is not None:
            wgauth.log(f"{name} works again")


def monitor(service, stop):
    errors = {}
    ticks = 0
    while not stop.wait(WATCH_INTERVAL):
        ticks += 1
        run_logged(errors, "copy detection", lambda: service.watch(current_state()))
        if ticks % (SYNC_INTERVAL // WATCH_INTERVAL) == 0:
            # rebuilds the gate if it's missing, ends the sessions no longer valid
            run_logged(errors, "sync", lambda: sync(apply=False))


def dns_reply(state, source, query):
    """
    Answer a DNS query that nftables redirected from a peer that isn't logged in, see wgauth.dns_answer.
    Returns None for clients that aren't such a peer: nobody else must get these answers.
    """
    if not state["redirect"]:
        return None
    server, _peer = wgauth.find_peer(state, source)
    if server is None:
        return None
    return wgauth.dns_answer(query, state["servers"][server]["address"])


def open_dns_socket(port):
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        sock.bind(("0.0.0.0", port))
    except OSError:
        sock.close()
        raise
    sock.settimeout(1)
    return sock


def serve_dns(stop):
    port, sock, failed = None, None, None
    while not stop.is_set():
        # the port can change when the configuration is applied
        wanted = current_state()["dns_port"]
        if wanted != port or sock is None:
            if sock is not None:
                sock.close()
            port, sock = wanted, None
            try:
                sock = open_dns_socket(wanted)
            except OSError as error:
                if failed != wanted:
                    wgauth.log(f"cannot answer DNS on port {wanted}: {error}", syslog.LOG_ERR)
                    failed = wanted
                stop.wait(SYNC_INTERVAL)
                continue
            failed = None
        try:
            query, (source, source_port) = sock.recvfrom(512)
            reply = dns_reply(current_state(), source, query)
            if reply is not None:
                sock.sendto(reply, (source, source_port))
        except TimeoutError:
            continue
        except Exception as error:  # noqa: BLE001 a bad packet must not stop the answers
            wgauth.log(f"DNS answer failed: {error}", syslog.LOG_ERR)
    if sock is not None:
        sock.close()


def serve():
    try:
        os.unlink(SOCKET)
    except FileNotFoundError:
        pass
    server = socketserver.ThreadingUnixStreamServer(SOCKET, Handler)
    os.chmod(SOCKET, 0o600)
    server.daemon_threads = True
    server.service = LoginService()
    stop = threading.Event()
    threading.Thread(target=monitor, args=(server.service, stop), daemon=True).start()
    threading.Thread(target=serve_dns, args=(stop,), daemon=True).start()
    wgauth.log("login service started")
    try:
        server.serve_forever()
    finally:
        stop.set()


def service_listening():
    try:
        with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as client:
            client.settimeout(2)
            client.connect(SOCKET)
    except OSError:
        return False
    return True


def check():
    """Test on the firewall what can't be tested elsewhere. Returns the exit code."""
    errors = 0

    def report(level, message):
        nonlocal errors
        print(f"{level:8}{message}")
        if level == "ERROR":
            errors += 1

    uci = EUci()
    state = current_state()
    servers = sorted(state["servers"])
    # without gated servers the rules are tested with a sample interface name
    sample = servers or ["wg1"]
    redirect = (state["redirect_port"], state["dns_port"]) if state["redirect"] else None
    for name, script in (
        ("login rules", wgauth.build_ruleset(sample, state["port"], redirect)),
        ("fallback rules", wgauth.build_block_ruleset(sample)),
    ):
        error = wgauth.check_script(script)
        report("OK" if error is None else "ERROR", f"nftables accepts the {name}" + (f": {error}" if error else ""))
    if os.path.exists(NGINX_MAIN_CONF):
        valid, message = nginx_test()
        report("OK" if valid else "ERROR", "nginx accepts its configuration" + ("" if valid else f": {message}"))
    if wgauth.list_gated_servers(uci) != servers:
        report("WARNING", "the servers that require the login changed, apply the changes to use them")
    if not servers:
        report("OK", "no WireGuard server requires the login")
        return 1 if errors else 0
    blocked = wgauth.gate_status()["blocked"]
    if blocked:
        report("ERROR", f"the VPN of {', '.join(blocked)} is blocked: the login rules couldn't be loaded")
    elif wgauth.table_matches(wgauth.read_table(), servers, wgauth.ruleset_for(state)):
        report("OK", f"the gate is in place for {', '.join(servers)}")
    else:
        report("ERROR", f"the gate is missing or incomplete for {', '.join(servers)}")
    if os.path.exists(NGINX_CONF):
        report("OK", f"the login page is configured on port {state['port']}")
    else:
        report("ERROR", "the login page isn't configured in nginx")
    if state["redirect"]:
        report(
            "OK",
            f"before the login, plain http:// addresses lead to the login page (web port {state['redirect_port']}, "
            f"DNS port {state['dns_port']}), if the DNS queries of the peers go through the tunnel",
        )
    report("OK" if service_listening() else "ERROR", f"the login service answers on {SOCKET}")
    endpoints = wgauth.read_endpoints() or {}
    stored_devices = wgauth.load_devices()
    for server in servers:
        by_address = {}
        by_user = {}
        config = state["servers"][server]
        if config["device_binding"]:
            if not shutil.which("openssl"):
                report("ERROR", f"{server} requires device binding but openssl is missing: nobody can log in")
            elif not config["public_key"]:
                report("ERROR", f"the public key of {server} is unknown: its devices can't log in")
            else:
                report("OK", f"{server} requires device binding" + (" and machine IDs" if config["machine_id"] else ""))
        for peer in config["peers"].values():
            if config["device_binding"] and peer["user"]:
                entry = wgauth.peer_device(stored_devices, peer["peer"], peer["public_key"])
                if wgauth.device_state(entry) == "closed":
                    report(
                        "WARNING",
                        f"peer {peer['peer']} of {server} has no device and its enrollment is closed: it can't log in "
                        "until an administrator allows the enrollment",
                    )
            if peer["user"]:
                by_user.setdefault(peer["user"].lower(), []).append(peer["peer"])
            if not peer["user"]:
                report("WARNING", f"peer {peer['peer']} of {server} has no user: it can't log in")
            elif wgauth.otp_missing(state, server, peer):
                report(
                    "WARNING",
                    f"user {peer['user']} of peer {peer['peer']} of {server} has no OTP secret: it can't log in, "
                    "save the peer again to create one and send the user the new QR code",
                )
            if endpoints.get(peer["public_key"]):
                by_address.setdefault(endpoints[peer["public_key"]], []).append(peer["peer"])
        for address, peers in sorted(by_address.items()):
            if len(peers) > 1:
                report(
                    "WARNING",
                    f"peers {', '.join(peers)} of {server} send from the same public IP {address}: if they are on "
                    "different networks, the router in front of the firewall hides the IPs of the clients, "
                    "set lock_endpoint to 0",
                )
        for user, peers in sorted(by_user.items()):
            if len(peers) > 1:
                report(
                    "WARNING",
                    f"user {user} has the peers {', '.join(sorted(peers))} on {server}: a user has one peer per server, "
                    "link the others to their own users or delete them",
                )
    return 1 if errors else 0


def status():
    gate = wgauth.gate_status()
    metadata = wgauth.load_metadata()
    now = time.time()
    result = []
    for server, elements in sorted(gate["sessions"].items()):
        for address, left in sorted(elements.items()):
            entry = metadata.get(server, {}).get(address, {})
            result.append(
                {
                    "server": server,
                    "address": address,
                    "peer": entry.get("peer", ""),
                    "user": entry.get("user", ""),
                    "from": entry.get("endpoint", ""),
                    "expires": iso_time(now + left),
                }
            )
    print(json.dumps({"sessions": result, "blocked_servers": gate["blocked"]}, indent=2))


def logout(peer):
    uci = EUci()
    section_type = uci.get("network", peer, default="")
    address = uci.get("network", peer, "ns_ip", default="")
    if not section_type.startswith("wireguard_") or not address:
        print(f"{peer} is not a WireGuard peer", file=sys.stderr)
        return 1
    if not wgauth.close_session(section_type[len("wireguard_") :], address, "administrator"):
        print(f"{peer} has no open session", file=sys.stderr)
    return 0


def alerts():
    result = {}
    for peer, entry in sorted(wgauth.load_alerts().items()):
        events = [dict(event, time=iso_time(event.get("time", 0))) for event in entry.get("events", [])]
        result[peer] = {"blocked": bool(entry.get("blocked")), "events": events}
    print(json.dumps(result, indent=2))


def devices():
    result = {}
    now = int(time.time())
    for peer, entry in sorted(wgauth.load_devices().items()):
        if not isinstance(entry, dict):
            continue
        item = {"state": wgauth.device_state(entry, now)}
        if item["state"] == "waiting":
            item["enrollment_until"] = iso_time(entry.get("window_until", 0))
        device = entry.get("device")
        if isinstance(device, dict):
            item.update(
                name=device.get("name", ""),
                kind=device.get("kind", ""),
                machine_id=bool(device.get("machine_id")),
                enrolled=iso_time(device.get("enrolled", 0)),
                last_used=iso_time(device.get("last_used", 0)),
                **{"from": device.get("endpoint", "")},
            )
        result[peer] = item
    print(json.dumps(result, indent=2))


def main():
    command = sys.argv[1] if len(sys.argv) > 1 else ""
    if command == "sync":
        sync(apply=True)
    elif command == "serve":
        serve()
    elif command == "check":
        sys.exit(check())
    elif command == "needed":
        sys.exit(0 if wgauth.list_gated_servers(EUci()) else 1)
    elif command == "status":
        status()
    elif command == "logout" and len(sys.argv) == 3:
        sys.exit(logout(sys.argv[2]))
    elif command == "alerts":
        alerts()
    elif command == "clear" and len(sys.argv) == 3:
        if not wgauth.clear_alerts(sys.argv[2]):
            print(f"{sys.argv[2]} has no alerts", file=sys.stderr)
    elif command == "devices":
        devices()
    else:
        print(__doc__.strip(), file=sys.stderr)
        sys.exit(2)


if __name__ == "__main__":
    main()
