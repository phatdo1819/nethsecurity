"""
Login page backend for the WireGuard servers that require user credentials.

Usage: ns-wgauth COMMAND

  sync            create or update the nftables gate and the nginx server, end the sessions no longer valid
  serve           run the login API on a unix socket, behind nginx
  needed          exit with 0 if at least one WireGuard server requires the login
  status          print the open sessions as JSON
  logout PEER     end the session of a peer, PEER is the peer section name
"""

import ipaddress
import json
import os
import socketserver
import subprocess
import sys
import syslog
import threading
import time
from datetime import UTC, datetime
from http.server import BaseHTTPRequestHandler

from euci import EUci
from nethsec import wgauth

SOCKET = "/var/run/ns-wgauth.sock"
NGINX_CONF = "/etc/nginx/conf.d/ns-wgauth.conf"
NGINX_MAIN_CONF = "/etc/nginx/uci.conf"
WEB_ROOT = "/www-wgauth"
# seconds: also the longest time a copied configuration can share a session, see lock_endpoint
SYNC_INTERVAL = 15
MAX_BODY = 4096
DEFAULT_MAX_FAILURES = 5
DEFAULT_LOCKOUT_TIME = 900
OTP_REUSE_WINDOW = 120

NGINX_TEMPLATE = """# Generated by ns-wgauth from /etc/config/ns-wgauth, do not edit
limit_req_zone $binary_remote_addr zone=ns_wgauth:1m rate=10r/m;

server {{
	listen {port};
	server_name _;
	root {root};
	access_log off;
	error_log syslog:server=unix:/dev/log,nohostname;
	server_tokens off;
	client_max_body_size 4k;
	add_header Cache-Control "no-store" always;
	add_header X-Content-Type-Options "nosniff" always;
	add_header X-Frame-Options "DENY" always;
	add_header Content-Security-Policy "default-src 'self'; frame-ancestors 'none'" always;

	location = / {{
		try_files /index.html =404;
	}}

	location / {{
		try_files $uri =404;
	}}

	location = /api/login {{
		limit_req zone=ns_wgauth burst=5 nodelay;
		limit_req_status 429;
		proxy_set_header X-Real-IP $remote_addr;
		proxy_set_header X-Forwarded-Host $http_host;
		proxy_pass http://unix:{socket};
	}}

	location /api/ {{
		proxy_set_header X-Real-IP $remote_addr;
		proxy_set_header X-Forwarded-Host $http_host;
		proxy_pass http://unix:{socket};
	}}
}}
"""


def iso_time(timestamp):
    return datetime.fromtimestamp(timestamp, tz=UTC).isoformat()


def read_file(path):
    try:
        with open(path) as fp:
            return fp.read()
    except FileNotFoundError:
        return None


def write_file(path, content):
    if content is None:
        if os.path.exists(path):
            os.remove(path)
        return
    with open(path, "w") as fp:
        fp.write(content)


def nginx_test():
    process = subprocess.run(["nginx", "-t", "-c", NGINX_MAIN_CONF], check=False, capture_output=True, text=True)
    return process.returncode == 0, process.stderr.strip()


def update_nginx(uci, servers):
    """
    Write the nginx server of the login page, remove it when no server requires the login.
    A configuration that nginx refuses is removed: the administration UI is served by the same nginx.
    """
    content = None
    if servers:
        content = NGINX_TEMPLATE.format(port=wgauth.get_port(uci), root=WEB_ROOT, socket=SOCKET)
    previous = read_file(NGINX_CONF)
    if previous == content:
        return
    write_file(NGINX_CONF, content)
    # at boot nginx hasn't generated its configuration yet: it will read the new file when it starts
    if os.path.exists(NGINX_MAIN_CONF):
        valid, message = nginx_test()
        if not valid:
            write_file(NGINX_CONF, previous)
            wgauth.log(f"nginx refused the login page configuration: {message}", syslog.LOG_ERR)
            return
    if subprocess.run(["/etc/init.d/nginx", "running"], check=False, capture_output=True).returncode == 0:
        subprocess.run(["/etc/init.d/nginx", "reload"], check=False, capture_output=True)


def sync(force=True):
    uci = EUci()
    with wgauth.state_lock():
        servers = wgauth.apply_ruleset(uci, force)
        update_nginx(uci, servers)
        wgauth.reconcile(uci)
    return servers


def get_int_option(uci, option, default):
    try:
        return max(int(uci.get("ns-wgauth", "config", option, default=default)), 1)
    except (TypeError, ValueError):
        return default


class LoginService:
    """The login API: every method returns an HTTP status and a JSON object."""

    def __init__(self):
        self.lock = threading.Lock()
        # peer -> timestamps of the recent failed logins
        self.failures = {}
        # (database, user) -> {code: timestamp}, an OTP code works only once
        self.used_codes = {}

    @staticmethod
    def target(uci, address, host):
        """
        Return the server and the peer of the client, `(None, None)` if it can't use the login page.
        The page must be opened with the address of the server: a page of another site whose name resolves to
        that address (DNS rebinding) is refused.
        """
        if address is None:
            return None, None
        server, peer = wgauth.find_peer(uci, address)
        if server is None:
            return None, None
        server_address = wgauth.get_server_address(uci, server)
        if host not in (server_address, f"{server_address}:{wgauth.get_port(uci)}"):
            return None, None
        return server, peer

    def status(self, address, host):
        uci = EUci()
        server, _peer = self.target(uci, address, host)
        if server is None:
            return 403, {"error": "forbidden"}
        result = {
            "authenticated": False,
            "otp_required": wgauth.requires_otp(uci, server),
            "server": uci.get("network", server, "ns_name", default=server),
        }
        left = wgauth.list_sessions().get(server, {}).get(address)
        if left is not None:
            entry = wgauth.load_metadata().get(server, {}).get(address, {})
            result["authenticated"] = True
            result["user"] = entry.get("user", "")
            result["expires"] = iso_time(time.time() + left)
        return 200, result

    def locked_until(self, peer, now, max_failures, lockout_time):
        with self.lock:
            recent = [moment for moment in self.failures.get(peer, []) if now - moment < lockout_time]
            self.failures[peer] = recent
            if len(recent) >= max_failures:
                return recent[-1] + lockout_time
        return None

    def code_reused(self, uci, server, user, code, now):
        key = (uci.get("network", server, "ns_user_db", default=""), user.get("name", "").lower())
        with self.lock:
            codes = {
                used: moment for used, moment in self.used_codes.get(key, {}).items() if now - moment < OTP_REUSE_WINDOW
            }
            reused = code in codes
            if not reused:
                codes[code] = now
            self.used_codes[key] = codes
        return reused

    def login(self, address, host, data):
        uci = EUci()
        server, peer = self.target(uci, address, host)
        if server is None:
            return 403, {"error": "forbidden"}
        now = time.time()
        max_failures = get_int_option(uci, "max_failures", DEFAULT_MAX_FAILURES)
        lockout_time = get_int_option(uci, "lockout_time", DEFAULT_LOCKOUT_TIME)
        until = self.locked_until(peer, now, max_failures, lockout_time)
        if until is not None:
            return 429, {"error": "too_many_attempts", "retry_after": max(int(until - now), 1)}
        username = data.get("username")
        otp = data.get("otp", "")
        user = wgauth.check_credentials(uci, server, peer, username, data.get("password"), otp)
        if user is not None and wgauth.requires_otp(uci, server) and self.code_reused(uci, server, user, otp, now):
            user = None
        if user is None:
            with self.lock:
                self.failures.setdefault(peer, []).append(now)
                failures = len(self.failures[peer])
            name = username[:64] if isinstance(username, str) else ""
            wgauth.log(
                f"login failed: user={name!r} server={server} peer={peer} address={address} failures={failures}",
                syslog.LOG_WARNING,
            )
            return 401, {"error": "invalid_credentials"}
        with self.lock:
            self.failures.pop(peer, None)
        expires = wgauth.open_session(uci, server, peer, address, user)
        return 200, {"result": "success", "user": user.get("name", ""), "expires": iso_time(expires)}

    def logout(self, address, host, data):
        uci = EUci()
        server, _peer = self.target(uci, address, host)
        if server is None:
            return 403, {"error": "forbidden"}
        wgauth.close_session(server, address, "logout")
        return 200, {"result": "success"}


class Handler(BaseHTTPRequestHandler):
    server_version = "ns-wgauth"
    sys_version = ""
    # seconds, nginx sends the whole request at once
    timeout = 10

    def log_message(self, format, *args):
        # logins are logged by LoginService, nothing else is worth it
        pass

    def address_string(self):
        return self.headers.get("X-Real-IP", "-") if getattr(self, "headers", None) else "-"

    def client_ip(self):
        # nginx sets the header, the socket is reachable only by root
        try:
            return str(ipaddress.IPv4Address(self.headers.get("X-Real-IP", "")))
        except ValueError:
            return None

    def host(self):
        return self.headers.get("X-Forwarded-Host", "")

    def route(self):
        return self.path.split("?", 1)[0]

    def send_json(self, status, data):
        body = json.dumps(data).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def read_json(self):
        # a form on another site can't send application/json without a CORS preflight, which this API never answers
        if self.headers.get_content_type() != "application/json":
            return None
        try:
            length = int(self.headers.get("Content-Length", "0"))
        except ValueError:
            return None
        if length < 0 or length > MAX_BODY:
            return None
        try:
            data = json.loads(self.rfile.read(length) or b"{}")
        except ValueError:
            return None
        return data if isinstance(data, dict) else None

    def call(self, method, *args):
        try:
            self.send_json(*method(self.client_ip(), self.host(), *args))
        except Exception as error:  # noqa: BLE001 answer the client and keep serving
            wgauth.log(f"request failed: {self.route()}: {error}", syslog.LOG_ERR)
            self.send_json(500, {"error": "internal_error"})

    def do_GET(self):
        if self.route() == "/api/status":
            self.call(self.server.service.status)
        else:
            self.send_json(404, {"error": "not_found"})

    def do_POST(self):
        methods = {"/api/login": self.server.service.login, "/api/logout": self.server.service.logout}
        method = methods.get(self.route())
        if method is None:
            self.send_json(404, {"error": "not_found"})
            return
        data = self.read_json()
        if data is None:
            self.send_json(400, {"error": "invalid_request"})
            return
        self.call(method, data)


def sync_loop(stop):
    while not stop.wait(SYNC_INTERVAL):
        try:
            # rebuilds the gate if it's missing, ends the sessions no longer valid
            sync(force=False)
        except Exception as error:  # noqa: BLE001 the loop must survive any error and retry
            wgauth.log(f"sync failed: {error}", syslog.LOG_ERR)


def serve():
    try:
        os.unlink(SOCKET)
    except FileNotFoundError:
        pass
    server = socketserver.ThreadingUnixStreamServer(SOCKET, Handler)
    os.chmod(SOCKET, 0o600)
    server.daemon_threads = True
    server.service = LoginService()
    stop = threading.Event()
    threading.Thread(target=sync_loop, args=(stop,), daemon=True).start()
    wgauth.log("login service started")
    try:
        server.serve_forever()
    finally:
        stop.set()


def status():
    sessions = wgauth.list_sessions()
    metadata = wgauth.load_metadata()
    now = time.time()
    result = []
    for server, elements in sorted(sessions.items()):
        for address, left in sorted(elements.items()):
            entry = metadata.get(server, {}).get(address, {})
            result.append(
                {
                    "server": server,
                    "address": address,
                    "peer": entry.get("peer", ""),
                    "user": entry.get("user", ""),
                    "expires": iso_time(now + left),
                }
            )
    print(json.dumps({"sessions": result}, indent=2))


def logout(peer):
    uci = EUci()
    section_type = uci.get("network", peer, default="")
    address = uci.get("network", peer, "ns_ip", default="")
    if not section_type.startswith("wireguard_") or not address:
        print(f"{peer} is not a WireGuard peer", file=sys.stderr)
        return 1
    if not wgauth.close_session(section_type[len("wireguard_") :], address, "administrator"):
        print(f"{peer} has no open session", file=sys.stderr)
    return 0


def main():
    command = sys.argv[1] if len(sys.argv) > 1 else ""
    if command == "sync":
        sync(force=True)
    elif command == "serve":
        serve()
    elif command == "needed":
        sys.exit(0 if wgauth.list_gated_servers(EUci()) else 1)
    elif command == "status":
        status()
    elif command == "logout" and len(sys.argv) == 3:
        sys.exit(logout(sys.argv[2]))
    else:
        print(__doc__.strip(), file=sys.stderr)
        sys.exit(2)


if __name__ == "__main__":
    main()
